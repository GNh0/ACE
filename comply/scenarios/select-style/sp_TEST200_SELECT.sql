CREATE PROCEDURE [dbo].[sp_TEST200_SELECT]
      @ORGDIV VARCHAR(2)
    , @FRDT   VARCHAR(8)
    , @TODT   VARCHAR(8)
    , @CUSTCD VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    WITH IN_SUM AS (
        SELECT A.ORGDIV, A.PURNUM, A.PURSEQ2, SUM(A.QTY) AS INQTY
        FROM DBO.XM210T A
        WHERE A.ORGDIV = @ORGDIV
        GROUP BY A.ORGDIV, A.PURNUM, A.PURSEQ2
        HAVING SUM(A.QTY) > 0
    )
    SELECT A.PURNUM, A.PURSEQ2, A.ITEMCD, B.ITEMNM, C.CUSTNM,
           FORMAT(A.QTY, '##0') AS QTY, ISNULL(D.INQTY, 0) AS INQTY,
           ISNULL(A.LOTNUM, A.PURNUM) AS LOTNUM
    FROM DBO.XX110T A
    INNER JOIN MS020T B ON B.ORGDIV = A.ORGDIV AND B.ITEMCD = A.ITEMCD
    INNER JOIN MS030T C ON C.ORGDIV = A.ORGDIV AND C.CUSTCD = A.CUSTCD AND C.USEYN = 'Y'
    LEFT JOIN IN_SUM D ON D.ORGDIV = A.ORGDIV AND D.PURNUM = A.PURNUM AND D.PURSEQ2 = A.PURSEQ2
    WHERE A.ORGDIV = @ORGDIV
      AND A.PURDT BETWEEN @FRDT AND @TODT
      AND (@CUSTCD = '' OR A.CUSTCD = @CUSTCD)
      AND NULLIF(A.LOTNUM, '') IS NOT NULL
    ORDER BY A.PURNUM, A.PURSEQ2
END
